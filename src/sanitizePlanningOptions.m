function planningOptions = sanitizePlanningOptions(planningOptions)
    legacyFields = { ...
        'preventStartingInfeasibleSprayLeg', ...
        'combineTouchingFields', ...
        'combineFieldTouchTolerance_m', ...
        'combineFieldAxisTolerance_deg', ...
        'combineSeparatedNearbyFields', ...
        'combineFieldGapThreshold_m', ...
        'combineRequiredCrossTrackOverlap_m', ...
        'combinedBlockLaneOrientationMode'};

    for i = 1:numel(legacyFields)
        if isfield(planningOptions, legacyFields{i})
            planningOptions = rmfield(planningOptions, legacyFields{i});
        end
    end
end
