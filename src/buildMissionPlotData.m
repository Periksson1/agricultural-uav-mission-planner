function plotData = buildMissionPlotData(~, planningData, simulationData)
    plotData = struct();
    plotData.fieldInfo = planningData.fieldInfo;
    plotData.fieldVisitOrder = planningData.fieldVisitOrder;
    plotData.fieldCount = planningData.fieldCount;
    plotData.fieldFirstCheckpoints = planningData.fieldFirstCheckpoints;
    plotData.fieldSummaryLines = planningData.fieldSummaryLines;
    plotData.baseDisplayXYZ = simulationData.baseDisplayXYZ;
    plotData.displayPathXYZ = simulationData.displayPathXYZ;
    plotData.displayPathTimeReal = simulationData.displayPathTimeReal;
    plotData.displaySegmentModes = simulationData.displaySegmentModes;
    plotData.displaySegmentStages = simulationData.displaySegmentStages;
    plotData.displaySegmentPass = simulationData.displaySegmentPass;
    plotData.displaySegmentSortie = simulationData.displaySegmentSortie;
    plotData.payloadInterruptPoints = simulationData.payloadInterruptPoints;
    plotData.batteryInterruptPoints = simulationData.batteryInterruptPoints;
    plotData.payloadInterruptSorties = simulationData.payloadInterruptSorties;
    plotData.batteryInterruptSorties = simulationData.batteryInterruptSorties;
    plotData.playbackModes = simulationData.playbackModes;
    plotData.playbackModeNames = simulationData.playbackModeNames;
    plotData.sortieLines = simulationData.sortieLines;
    plotData.passCompletionMissionTime = simulationData.passCompletionMissionTime;
    plotData.pathXYZ = simulationData.pathXYZ;
    plotData.pathTime = simulationData.pathTime;
    plotData.totalTime = simulationData.totalTime;
    plotData.stateInterp = simulationData.stateInterp;
    plotData.groundStationX = planningData.groundStationX;
    plotData.groundStationY = planningData.groundStationY;
    plotData.groundStationZ = planningData.groundStationZ;
end
